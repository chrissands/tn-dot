/**
 * Builds styles/uswds-critical.css: the rules of styles/uswds-core.css that the site's
 * pages actually use at first render, measured with Chrome CSS rule-usage coverage on the
 * local preview (representative pages x breakpoint widths). head.html loads this subset;
 * scripts.js loads the full uswds-core.css after first render, inserted before the subset
 * so rule order (and therefore the cascade) is unchanged. Keeps every @font-face and
 * @keyframes rule.
 *
 * Re-run after changing blocks/templates or upgrading USWDS:
 *   node tools/perf/build-uswds-critical.cjs   (local preview running on :3000)
 */
const fs = require('fs');
const path = require('path');
const postcss = require('postcss');
const { chromium } = require('playwright');

const ROOT = path.resolve(__dirname, '../..');
const BASE = process.env.PREVIEW || 'http://localhost:3000/content';
const CORE = path.join(ROOT, 'styles/uswds-core.css');
const OUT = path.join(ROOT, 'styles/uswds-critical.css');

// one or more pages per template / block mix
const PAGES = [
  '/index', '/news', '/news?page=2', '/news?category=news',
  '/news/2026/9/10/design-public-meetings-scheduled',
  '/news/2026/9/25/two-bridge-replacement-projects-to-begin-utility-work-in-sumner-county',
  '/news/2026/9/24/middle-tennessee-scheduled-lane-closures-september-27-october-3-2026',
  '/maintenance/maintenance-request',
  '/local-programs-community-investments/community-investments-office/highway-beautification-office/beautification-national-scenic-byways',
  '/driver-how-do-i/find-traveler-information',
  '/traffic-operations-division/yellow-dot-program',
];
// USWDS (480/640/1024) and site (600/900/1200) breakpoints on both sides
const WIDTHS = [375, 480, 600, 640, 900, 1024, 1200, 1440];

(async () => {
  const coreText = fs.readFileSync(CORE, 'utf8');
  const used = [];
  const b = await chromium.launch();
  for (const width of WIDTHS) {
    const ctx = await b.newContext({ viewport: { width, height: 900 } });
    for (const page of PAGES) {
      const p = await ctx.newPage();
      const cdp = await ctx.newCDPSession(p);
      const sheets = new Map();
      cdp.on('CSS.styleSheetAdded', ({ header }) => sheets.set(header.styleSheetId, header.sourceURL));
      await cdp.send('DOM.enable');
      await cdp.send('CSS.enable');
      await cdp.send('CSS.startRuleUsageTracking');
      await p.goto(`${BASE}${page}`, { waitUntil: 'load' });
      await p.waitForTimeout(2500);
      const h = await p.evaluate(() => document.body.scrollHeight);
      for (let y = 0; y < h; y += 700) { await p.evaluate((yy) => window.scrollTo(0, yy), y); await p.waitForTimeout(80); }
      await p.waitForTimeout(800);
      const { ruleUsage } = await cdp.send('CSS.stopRuleUsageTracking');
      ruleUsage.filter((r) => r.used && /\/styles\/uswds-core\.css/.test(sheets.get(r.styleSheetId) || ''))
        .forEach((r) => used.push([r.startOffset, r.endOffset]));
      await p.close();
    }
    await ctx.close();
    process.stdout.write(`${width} `);
  }
  await b.close();

  const starts = new Set(used.map(([s]) => s));
  const root = postcss.parse(coreText);
  let kept = 0;
  let dropped = 0;
  root.walkRules((rule) => {
    if (rule.parent && rule.parent.type === 'atrule' && /keyframes$/i.test(rule.parent.name)) return;
    const s = rule.source.start.offset;
    const e = rule.source.end.offset;
    const hit = starts.has(s) || used.some(([us]) => us >= s && us <= e);
    if (hit) kept += 1; else { rule.remove(); dropped += 1; }
  });
  // drop at-rules left empty (media / supports) – keep font-face and keyframes
  root.walkAtRules((at) => {
    if (/^(font-face|keyframes|-webkit-keyframes)$/i.test(at.name)) return;
    if (at.nodes && !at.nodes.length) at.remove();
  });
  root.walkComments((c) => c.remove());
  const header = `/* Generated by tools/perf/build-uswds-critical.cjs – do not edit.
 * USWDS rules used at first render (${kept} of ${kept + dropped}); the full
 * uswds-core.css is loaded after first render by scripts.js. */\n`;
  fs.writeFileSync(OUT, header + root.toString().replace(/\n{3,}/g, '\n\n'));
  const size = fs.statSync(OUT).size;
  console.log(`\nkept ${kept} / ${kept + dropped} rules -> ${OUT.replace(`${ROOT}/`, '')} (${Math.round(size / 1024)} KB)`);
})();
